-----YTD SALE----
WITH YTD
AS (
	SELECT D.STORE_SID
		,SUM((NVL(D.SALE_SUBTOTAL_WITH_TAX, 0) - NVL(D.RETURN_SUBTOTAL_WITH_TAX, 0)) + (NVL(D.TOTAL_DEPOSIT_TAKEN, 0)) + (NVL(D.TOTAL_FEE_AMT, 0)) + NVL(D.shipping_amt, 0)) AS SALES
	FROM RPS.DOCUMENT D
	WHERE D.STATUS = 4
		AND EXTRACT(YEAR FROM D.INVC_POST_DATE) = EXTRACT(YEAR FROM SYSDATE)
	GROUP BY D.STORE_SID
	)
	,
	----MTD SALES----
MTD
AS (
	SELECT D.STORE_SID
		,SUM((NVL(D.SALE_SUBTOTAL_WITH_TAX, 0) - NVL(D.RETURN_SUBTOTAL_WITH_TAX, 0)) + (NVL(D.TOTAL_DEPOSIT_TAKEN, 0)) + (NVL(D.TOTAL_FEE_AMT, 0)) + NVL(D.shipping_amt, 0)) AS SALES
	FROM RPS.DOCUMENT D
	WHERE D.STATUS = 4
		AND EXTRACT(YEAR FROM D.INVC_POST_DATE) = EXTRACT(YEAR FROM SYSDATE)
		AND EXTRACT(MONTH FROM D.INVC_POST_DATE) = EXTRACT(MONTH FROM SYSDATE)
	GROUP BY D.STORE_SID
	)
	,
	----YESTERDAY SALES----
YDAY
AS (
	SELECT D.STORE_SID
		,SUM((NVL(D.SALE_SUBTOTAL_WITH_TAX, 0) - NVL(D.RETURN_SUBTOTAL_WITH_TAX, 0)) + (NVL(D.TOTAL_DEPOSIT_TAKEN, 0)) + (NVL(D.TOTAL_FEE_AMT, 0)) + NVL(D.shipping_amt, 0)) AS SALES
	FROM RPS.DOCUMENT D
	WHERE D.STATUS = 4
		AND TRUNC(D.INVC_POST_DATE) = TRUNC(SYSDATE - 1)
	GROUP BY D.STORE_SID
	)
	,
	----TODAY SALES----
TODAY
AS (
	SELECT D.STORE_SID
		,SUM((NVL(D.SALE_SUBTOTAL_WITH_TAX, 0) - NVL(D.RETURN_SUBTOTAL_WITH_TAX, 0)) + (NVL(D.TOTAL_DEPOSIT_TAKEN, 0)) + (NVL(D.TOTAL_FEE_AMT, 0)) + NVL(D.shipping_amt, 0)) AS SALES
	FROM RPS.DOCUMENT D
	WHERE D.STATUS = 4
		AND TRUNC(D.INVC_POST_DATE) = TRUNC(SYSDATE)
	GROUP BY D.STORE_SID
	)
	,
	----TOTAL SALES----
TOTAL
AS (
	SELECT D.STORE_SID
		,SUM((NVL(D.SALE_SUBTOTAL_WITH_TAX, 0) - NVL(D.RETURN_SUBTOTAL_WITH_TAX, 0)) + (NVL(D.TOTAL_DEPOSIT_TAKEN, 0)) + (NVL(D.TOTAL_FEE_AMT, 0)) + NVL(D.shipping_amt, 0)) AS SALES
	FROM RPS.DOCUMENT D
	WHERE D.STATUS = 4
	GROUP BY D.STORE_SID
	)
