SELECT SB.SBS_NO AS "Subsidiary No"
	,SB.SBS_Name AS "Subsidiary Name"
	,St.Store_NO AS "Store No"
	,St.Store_code AS "Store Code"
	,St.Store_Name AS "Store Name"
	,NVL(TODAY.SALES, 0) AS "Today Sales"
	,NVL(YDAY.SALES, 0) AS "Yesterday Sales"
	,NVL(MTD.SALES, 0) AS "MTD Sales"
	,NVL(YTD.SALES, 0) AS "YTD Sales"
	,NVL(TOTAL.SALES, 0) AS "Total Sales"
FROM RPS.STORE ST
INNER JOIN RPS.SUBSIDIARY SB ON ST.SBS_SID = SB.SID
LEFT JOIN YTD ON ST.SID = YTD.STORE_SID
LEFT JOIN MTD ON ST.SID = MTD.STORE_SID
LEFT JOIN YDAY ON ST.SID = YDAY.STORE_SID
LEFT JOIN TODAY ON ST.SID = TODAY.STORE_SID
LEFT JOIN TOTAL ON ST.SID = TOTAL.STORE_SID
ORDER BY SB.SBS_NO
	,ST.STORE_CODE
