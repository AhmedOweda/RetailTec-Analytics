/*-----------------------------------------------------------ITEM SOLD/PURCHASE/ADJUST/OUTSLIP/INSLIP PER PERIOD REPORT----------------------------------------------------------------------------*/
/*SALES*/
WITH
SALES AS (
		SELECT O.SUBSIDIARY_SID AS SBS_SID
			,O.STORE_SID
			,T.INVN_SBS_ITEM_SID AS ITEM_SID
			,SUM(CASE WHEN T.ITEM_TYPE = 1 THEN (T.QTY * - 1) ELSE T.QTY END) AS SOLD_QTY
		FROM RPS.DOCUMENT O
		LEFT JOIN RPS.DOCUMENT_ITEM T ON O.SID = T.DOC_SID
		WHERE T.ITEM_TYPE IN (1, 2)
			AND T.KIT_FLAG <> 3
			AND O.STATUS = 4
			AND O.IS_HELD <> 1
			AND O.DOC_NO > 0
			AND =-= TRUNC(o.CREATED_DATETIME) =-=
		GROUP BY O.SUBSIDIARY_SID
			,O.STORE_SID
			,T.INVN_SBS_ITEM_SID
		)
	,
	----------------------------------------------------
	/*PURCHASE*/
	PURCHASE AS (
		SELECT O.SBS_SID
			,O.STORE_SID
			,T.ITEM_SID
			,SUM(CASE WHEN O.VOU_TYPE = 1 THEN (T.QTY * - 1) ELSE T.QTY END) AS PURCHASED_QTY
		FROM RPS.VOUCHER O
		LEFT JOIN RPS.VOU_ITEM T ON O.SID = T.VOU_SID
		WHERE O.VOU_TYPE IN (0, 1)
			AND NVL(O.STATUS, 0) = 4
			AND NVL(O.VOU_NO, 0) > 0
			AND NVL(O.HELD, 0) = 0
			AND NVL(O.VOU_CLASS, 0) = 0
			AND NVL(O.REVERSED_FLAG, 0) = 0
			AND NVL(O.SLIP_FLAG, 0) = 0
			AND =-= TRUNC(o.CREATED_DATETIME) =-=
		GROUP BY O.SBS_SID
			,O.STORE_SID
			,T.ITEM_SID
		)
	,
	----------------------------------------------------
	/*INSLIP*/
	INSLIP AS (
		SELECT O.SBS_SID
			,O.STORE_SID
			,T.ITEM_SID
			,SUM(CASE WHEN O.VOU_TYPE = 1 THEN (T.QTY * - 1) ELSE T.QTY END) AS INSLIP_QTY
		FROM RPS.VOUCHER O
		LEFT JOIN RPS.VOU_ITEM T ON O.SID = T.VOU_SID
		WHERE O.VOU_TYPE IN (0, 1)
			AND NVL(O.STATUS, 0) = 4
			AND NVL(O.VOU_NO, 0) > 0
			AND NVL(O.HELD, 0) = 0
			AND NVL(O.VOU_CLASS, 0) = 0
			AND NVL(O.REVERSED_FLAG, 0) = 0
			AND NVL(O.SLIP_FLAG, 0) = 1
			AND =-= TRUNC(o.CREATED_DATETIME) =-=
		GROUP BY O.SBS_SID
			,O.STORE_SID
			,T.ITEM_SID
		)
	,
	------------------------------------------------ 
	/* ADJUSTMENT */
	ADJUST AS (
		SELECT O.SBS_SID
			,O.STORE_SID
			,T.ITEM_SID
			,SUM(NVL(T.ADJ_VALUE, 0) - NVL(T.ORIG_VALUE, 0)) AS ADJUST_QTY
		FROM RPS.ADJUSTMENT O
		LEFT JOIN RPS.ADJ_ITEM T ON O.SID = T.ADJ_SID
		WHERE NVL(O.ADJ_TYPE, 0) = 0
			AND NVL(O.HELD, 0) = 0
			AND NVL(O.STATUS, 0) = 4
			AND O.ADJ_NO > 0
			AND NVL(T.ITEM_NOTE1, 0) NOT LIKE 'PRISM%'
			AND =-= TRUNC(o.CREATED_DATETIME) =-=
		GROUP BY O.SBS_SID
			,O.STORE_SID
			,T.ITEM_SID
		)
	,
	------------------------------------------------ 
	/* OUTSLIP*/
	OUTSLIP AS (
		SELECT O.OUT_SBS_SID AS SBS_SID
			,O.OUT_STORE_SID AS STORE_SID
			,T.ITEM_SID
			,SUM(CASE WHEN NVL(O.REVERSED_FLAG, 0) = 2 THEN T.QTY ELSE T.QTY * - 1 END) AS OUTSLIP_QTY
		FROM RPS.SLIP O
		LEFT JOIN RPS.SLIP_ITEM T ON O.SID = T.SLIP_SID
		WHERE NVL(O.HELD, 0) = 0
			AND NVL(O.STATUS, 0) = 4
			AND NVL(O.SLIP_NO, 0) > 0
			AND =-= TRUNC(o.CREATED_DATETIME) =-=
		GROUP BY O.OUT_SBS_SID
			,O.OUT_STORE_SID
			,T.ITEM_SID
		)
	,
	--------------------------------------------------
	/*PRICE L 1*/
	PRICE1 AS (
		SELECT DISTINCT PR.PRICE
			,PR.INVN_SBS_ITEM_SID AS
		FROM RPS.INVN_SBS_PRICE PR
		INNER JOIN RPS.PRICE_LEVEL PL ON PL.SID = PR.PRICE_LVL_SID
		WHERE PL.PRICE_LVL = 1
		)
	,
	--------------------------------------------------
	/*PRICE L 2*/
	PRICE2 AS (
		SELECT DISTINCT PR.PRICE
			,PR.INVN_SBS_ITEM_SID AS
		FROM RPS.INVN_SBS_PRICE PR
		INNER JOIN RPS.PRICE_LEVEL PL ON PL.SID = PR.PRICE_LVL_SID
		WHERE PL.PRICE_LVL = 2
		)

